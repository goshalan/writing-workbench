  function detectLanguage() {
    var preferred = Array.isArray(navigator.languages) && navigator.languages.length
      ? navigator.languages
      : [navigator.language || "en"];
    return preferred.some(function (language) {
      return String(language).toLowerCase().indexOf("zh") === 0;
    }) ? "zh-CN" : "en";
  }

  var language = detectLanguage();
  var locale = language === "zh-CN" ? "zh-CN" : "en-US";

  function t(key, values) {
    var dictionary = messages[language] || messages.en;
    var template = dictionary[key];
    if (template == null) {
      template = messages.en[key];
    }
    if (template == null) {
      return key;
    }
    return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, function (_match, name) {
      return values && values[name] != null ? String(values[name]) : "";
    });
  }

  function errorMessage(code, fallback, status) {
    var key = "errors." + String(code || "");
    var translated = messages[language] && messages[language][key];
    if (translated) {
      return translated;
    }
    if (language === "zh-CN" && fallback) {
      return String(fallback);
    }
    return status ? t("status.requestFailedCode", { status: status }) : t("status.requestFailed");
  }

  function apply() {
    document.documentElement.lang = language;
    document.title = t("meta.title");
    var description = document.querySelector('meta[name="description"]');
    if (description) {
      description.setAttribute("content", t("meta.description"));
    }
    document.querySelectorAll("[data-i18n]").forEach(function (node) {
      node.textContent = t(node.dataset.i18n);
    });
    ["placeholder", "title", "aria-label"].forEach(function (attribute) {
      var dataAttribute = "data-i18n-" + attribute;
      document.querySelectorAll("[" + dataAttribute + "]").forEach(function (node) {
        node.setAttribute(attribute, t(node.getAttribute(dataAttribute)));
      });
    });
  }

  window.WritingWorkbenchI18n = {
    apply: apply,
    errorMessage: errorMessage,
    language: language,
    locale: locale,
    t: t
  };
